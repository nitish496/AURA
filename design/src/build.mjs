// Generates every derived design asset from the sources in design/src.
//   node design/src/build.mjs
// Outputs (all checked in):
//   app/src/main/res/drawable/ic_*.xml            icon family (VectorDrawable)
//   app/src/main/java/dev/lilt/player/ui/IconPaths.java
//   app/src/main/res/drawable/ic_launcher_foreground.xml, ic_launcher_monochrome.xml,
//   app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml, ic_launcher_round.xml,
//   app/src/main/res/drawable/aura_logo.xml, aura_wordmark.xml, ic_notification.xml
//   design/logo.svg, design/logo-mark.svg, design/app-icon.svg, design/tokens.json
//   design/prototype.html

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ICONS, ALIASES, STROKE } from './icons.mjs';
import { markPaths, markSize, wordmark, R, GAP, SHIFT } from './brand.mjs';
import * as tokens from './tokens.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const res = path.join(repo, 'app/src/main/res');
const write = (file, text) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); };
const GENERATED = 'Generated by design/src/build.mjs';
const WHITE = '#FFFFFFFF';

// ---------------------------------------------------------------- icons -> VectorDrawable
function vectorPath(layer) {
  const a = [`android:pathData="${layer.d}"`];
  if (layer.mode === 'f' || layer.mode === 'fe' || layer.mode === 'fs') a.push(`android:fillColor="${WHITE}"`);
  if (layer.mode === 'fe') a.push('android:fillType="evenOdd"');
  if (layer.mode === 's' || layer.mode === 'fs') {
    a.push(`android:strokeColor="${WHITE}"`, `android:strokeWidth="${STROKE}"`,
      'android:strokeLineCap="round"', 'android:strokeLineJoin="round"');
  }
  return `    <path\n        ${a.join('\n        ')} />`;
}
function iconXml(name) {
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- AURA icon "${name}". ${GENERATED} from design/src/icons.mjs; do not edit. -->\n` +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n` +
    `    android:viewportWidth="24"\n    android:viewportHeight="24">\n${ICONS[name].map(vectorPath).join('\n')}\n</vector>\n`;
}
const drawableDir = path.join(res, 'drawable');
for (const f of fs.existsSync(drawableDir) ? fs.readdirSync(drawableDir) : []) {
  if (!f.startsWith('ic_') || !f.endsWith('.xml')) continue;
  const text = fs.readFileSync(path.join(drawableDir, f), 'utf8');
  if (text.includes(GENERATED) && text.includes('design/src/icons.mjs')) fs.unlinkSync(path.join(drawableDir, f));
}
for (const name of Object.keys(ICONS)) write(path.join(drawableDir, `ic_${name}.xml`), iconXml(name));

// ---------------------------------------------------------------- icons -> IconPaths.java
{
  const names = Object.keys(ICONS).sort();
  const modeOf = { s: 'STROKE_ONLY', f: 'FILL', fe: 'FILL_EVEN_ODD', fs: 'FILL_AND_STROKE' };
  const java = `package dev.lilt.player.ui;

/**
 * Path data for the AURA icon family on a 24 x 24 grid.
 *
 * <p>${GENERATED} from design/src/icons.mjs, which also generates the
 * {@code res/drawable/ic_*.xml} vector drawables, so both always describe the same shapes.
 * Do not edit by hand. Pure Java: used by {@code GlyphDrawable} and by logic tests.
 */
public final class IconPaths {
    private IconPaths() {}

    /** Stroke width of outline layers, in viewport units (the viewport is 24 units square). */
    public static final float STROKE = ${STROKE}f;
    /** Layer is stroked with {@link #STROKE}, round caps and joins. */
    public static final int STROKE_ONLY = 0;
    /** Layer is filled (non-zero winding). */
    public static final int FILL = 1;
    /** Layer is filled with the even-odd rule (holes, e.g. the explicit badge). */
    public static final int FILL_EVEN_ODD = 2;
    /** Layer is filled and stroked, so the silhouette matches the outline variant. */
    public static final int FILL_AND_STROKE = 3;

    /** One icon: an ordered list of layers, each with SVG path data and a paint mode. */
    public static final class Glyph {
        public final String name;
        private final String[] paths;
        private final int[] modes;
        Glyph(String name, String[] paths, int[] modes) { this.name = name; this.paths = paths; this.modes = modes; }
        public int layers() { return paths.length; }
        public String path(int layer) { return paths[layer]; }
        public int mode(int layer) { return modes[layer]; }
    }

    private static final String[] NAMES = {
${names.map((nm) => `        "${nm}",`).join('\n')}
    };
    private static final String[][] PATHS = {
${names.map((nm) => `        { ${ICONS[nm].map((l) => JSON.stringify(l.d)).join(', ')} },`).join('\n')}
    };
    private static final int[][] MODES = {
${names.map((nm) => `        { ${ICONS[nm].map((l) => modeOf[l.mode]).join(', ')} },`).join('\n')}
    };
    private static final Glyph[] GLYPHS = new Glyph[NAMES.length];

    /** Icon names in sorted order (the same names as the {@code ic_<name>} drawables). */
    public static String[] names() { return NAMES.clone(); }

    /** The glyph for {@code name} (or a legacy alias such as "down"), or null when unknown. */
    public static synchronized Glyph get(String name) {
        if (name == null) return null;
        String resolved = alias(name);
        int index = java.util.Arrays.binarySearch(NAMES, resolved);
        if (index < 0) return null;
        if (GLYPHS[index] == null) GLYPHS[index] = new Glyph(NAMES[index], PATHS[index], MODES[index]);
        return GLYPHS[index];
    }

    /** Maps names used by the 1.x interface onto the current family. */
    public static String alias(String name) {
        switch (name) {
${Object.entries(ALIASES).map(([a, b]) => `            case "${a}": return "${b}";`).join('\n')}
            default: return name;
        }
    }
}
`;
  write(path.join(repo, 'app/src/main/java/dev/lilt/player/ui/IconPaths.java'), java);
}

// ---------------------------------------------------------------- brand
const INK = '#F5F5F7', GRAPHITE = '#151517';
const vector = (wdp, hdp, vw, vh, body, comment) =>
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${comment} ${GENERATED} from design/src/brand.mjs; do not edit. -->\n` +
  `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="${wdp}dp"\n    android:height="${hdp}dp"\n` +
  `    android:viewportWidth="${vw}"\n    android:viewportHeight="${vh}">\n${body}\n</vector>\n`;
const fillPaths = (paths, color) => paths.map((d) => `    <path\n        android:fillColor="${color}"\n        android:pathData="${d}" />`).join('\n');

// Adaptive launcher icon: 108dp layers; the mark (44dp wide) sits well inside the 66dp safe zone.
const LAUNCHER_K = 44 / markSize(1).w;
write(path.join(drawableDir, 'ic_launcher_foreground.xml'),
  vector(108, 108, 108, 108, fillPaths(markPaths(LAUNCHER_K, 54, 54), INK), 'AURA launcher foreground: the Refraction mark.'));
write(path.join(drawableDir, 'ic_launcher_monochrome.xml'),
  vector(108, 108, 108, 108, fillPaths(markPaths(LAUNCHER_K, 54, 54), WHITE), 'Themed-icon layer (Android 13+): only alpha is used.'));
const adaptive = `<?xml version="1.0" encoding="utf-8"?>\n<!-- AURA adaptive launcher icon. ${GENERATED}; do not edit. -->\n` +
  `<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n` +
  `    <background android:drawable="@color/ic_launcher_background" />\n` +
  `    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n` +
  `    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n</adaptive-icon>\n`;
write(path.join(res, 'mipmap-anydpi-v26/ic_launcher.xml'), adaptive);
write(path.join(res, 'mipmap-anydpi-v26/ic_launcher_round.xml'), adaptive);
write(path.join(res, 'values/ic_launcher_background.xml'),
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${GENERATED}; do not edit. -->\n<resources>\n    <color name="ic_launcher_background">${GRAPHITE}</color>\n</resources>\n`);
// Startup / about logo: mark at 1:1 in a 72-unit box shown at 108dp (about 64dp of mark).
write(path.join(drawableDir, 'aura_logo.xml'),
  vector(108, 108, 72, 72, fillPaths(markPaths(1, 36, 36), INK), 'AURA mark for the startup screen.'));
// Status-bar / notification icon: white, 20dp live area.
write(path.join(drawableDir, 'ic_notification.xml'),
  vector(24, 24, 24, 24, fillPaths(markPaths(20 / markSize(1).w, 12, 12), WHITE), 'AURA notification small icon.'));
// Wordmark drawable (outlines in font units, scaled by a group): 80 x 20dp at cap height 13.3dp.
{
  const wm = wordmark();
  const [x0, y0, x1, y1] = wm.bounds;
  const w = x1 - x0, h = y1 - y0;
  const body = `    <group\n        android:translateX="${-x0}"\n        android:translateY="${-y0}">\n` +
    `        <path\n            android:fillColor="${INK}"\n            android:pathData="${wm.d}" />\n    </group>`;
  const hdp = 16, wdp = +(hdp * w / h).toFixed(1);
  write(path.join(drawableDir, 'aura_wordmark.xml'), vector(wdp, hdp, Math.ceil(w), Math.ceil(h), body, 'AURA wordmark (Inter Display SemiBold).'));
}

// SVG brand files
{
  const wm = wordmark();
  const [x0, y0, x1, y1] = wm.bounds;
  const cap = 26, s = cap / wm.cap; // scale font units to a 26-unit cap height
  const markK = 37.7 / markSize(1).h;
  const mw = markSize(markK).w, gap = 14, pad = 0;
  const wmW = (x1 - x0) * s;
  const W = Math.ceil(pad * 2 + mw + gap + wmW), H = 40;
  const mark = markPaths(markK, pad + mw / 2, H / 2).map((d) => `<path d="${d}"/>`).join('');
  const word = `<path transform="translate(${(pad + mw + gap - x0 * s).toFixed(2)} ${(H / 2 + cap / 2).toFixed(2)}) scale(${s.toFixed(6)})" d="${wm.d}"/>`;
  const style = '<style>path{fill:#111113}@media (prefers-color-scheme:dark){path{fill:#F5F5F7}}</style>';
  write(path.join(repo, 'design/logo.svg'),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W * 4}" height="${H * 4}" role="img" aria-label="AURA">` +
    `<title>AURA</title>${style}${mark}${word}</svg>\n`);
  write(path.join(repo, 'design/logo-mark.svg'),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" width="192" height="192" role="img" aria-label="AURA mark">` +
    `<title>AURA mark</title>${style}${markPaths(1).map((d) => `<path d="${d}"/>`).join('')}</svg>\n`);
  const iconK = 620 / markSize(1).w;
  write(path.join(repo, 'design/app-icon.svg'),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024" role="img" aria-label="AURA app icon">` +
    `<title>AURA app icon</title><rect width="1024" height="1024" rx="230" fill="${GRAPHITE}"/>` +
    `${markPaths(iconK, 512, 512).map((d) => `<path d="${d}" fill="${INK}"/>`).join('')}</svg>\n`);
}

// ---------------------------------------------------------------- tokens.json
write(path.join(repo, 'design/tokens.json'), JSON.stringify({
  generatedBy: 'design/src/build.mjs', color: tokens.color, type: tokens.type, space: tokens.space,
  radius: tokens.radius, size: tokens.size, motion: tokens.motion,
  brand: { mark: { grid: 48, radius: R, gap: GAP, shift: SHIFT } },
}, null, 2) + '\n');

// ---------------------------------------------------------------- prototype
const { buildPrototype } = await import('./prototype.mjs');
write(path.join(repo, 'design/prototype.html'), buildPrototype());
console.log('design assets generated:', Object.keys(ICONS).length, 'icons');
