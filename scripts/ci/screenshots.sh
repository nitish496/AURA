#!/usr/bin/env bash
# Runs inside reactivecircus/android-emulator-runner on CI.
# Usage: screenshots.sh APK_DIR MEDIA_DIR OUT_DIR
set -uo pipefail
APK_DIR=$1; MEDIA=$2; OUT=$3
PKG=dev.lilt.player
ACT=$PKG/.MainActivity
mkdir -p "$OUT/raw"
log() { echo "[shots] $*"; echo "$*" >> "$OUT/raw/capture-log.txt"; }

adb wait-for-device
until [ "$(adb shell getprop sys.boot_completed | tr -d '\r')" = "1" ]; do sleep 2; done
sleep 5

# Clean, consistent system chrome (Android demo mode), dark theme, gesture navigation.
adb shell settings put global sysui_demo_allowed 1
adb shell am broadcast -a com.android.systemui.demo -e command enter >/dev/null
adb shell am broadcast -a com.android.systemui.demo -e command clock -e hhmm 0941 >/dev/null
adb shell am broadcast -a com.android.systemui.demo -e command battery -e level 100 -e plugged false >/dev/null
adb shell am broadcast -a com.android.systemui.demo -e command network -e wifi show -e level 4 >/dev/null
adb shell am broadcast -a com.android.systemui.demo -e command network -e mobile show -e datatype none -e level 4 >/dev/null
adb shell am broadcast -a com.android.systemui.demo -e command notifications -e visible false >/dev/null
adb shell cmd overlay enable com.android.internal.systemui.navbar.gestural || true
adb shell cmd uimode night yes || true

# Demo library: fictional albums generated by demo_media.py.
adb shell mkdir -p /sdcard/Music
adb push "$MEDIA/." /sdcard/Music/ >/dev/null
adb shell content call --method scan_volume --uri content://media --arg external_primary >/dev/null 2>&1 || true
for i in $(seq 1 30); do
  n=$(adb shell content query --uri content://media/external/audio/media --projection _id 2>/dev/null | grep -c Row || true)
  [ "${n:-0}" -ge 40 ] && break; sleep 2
done
log "MediaStore audio rows: ${n:-0}"

APK=$(ls "$APK_DIR"/*.apk | head -1)
adb install -r -g "$APK" || { log "install failed"; exit 1; }
adb shell pm grant $PKG android.permission.READ_MEDIA_AUDIO 2>/dev/null || true
adb shell pm grant $PKG android.permission.POST_NOTIFICATIONS 2>/dev/null || true
adb logcat -c

adb shell am start -W -n $ACT >/dev/null
sleep 8

while IFS='|' read -r name extras wait; do
  [[ -z "$name" || "$name" == \#* ]] && continue
  # </dev/null: adb would otherwise consume the rest of screens.txt from the loop's stdin.
  adb shell "am start -W --activity-single-top -n $ACT $extras" </dev/null >/dev/null 2>&1 || log "am start failed for $name"
  sleep "${wait:-5}"
  if [[ "$name" != _* ]]; then
    adb exec-out screencap -p </dev/null > "$OUT/raw/$name.png" && log "captured $name"
  fi
done < "$(dirname "$0")/screens.txt"

# Optional short screen recording of scrolling Home (glass bar over moving content).
if [ "${RECORD_VIDEO:-0}" = "1" ]; then
adb shell "am start -W --activity-single-top -n $ACT --es aura.screen home --es aura.theme dark" >/dev/null 2>&1
sleep 4
adb shell screenrecord --time-limit 8 --bit-rate 2500000 /sdcard/scroll.mp4 &
REC=$!
sleep 1
adb shell input swipe 540 1800 540 700 600; sleep 1.5
adb shell input swipe 540 1800 540 600 500; sleep 1.5
adb shell input swipe 540 700 540 1800 600; sleep 2
wait $REC 2>/dev/null
adb pull /sdcard/scroll.mp4 "$OUT/raw/scroll.mp4" >/dev/null 2>&1 || true
fi

{
  echo "== crash buffer =="; adb logcat -d -b crash
  echo "== AndroidRuntime / AURA errors =="; adb logcat -d -v brief '*:E' | grep -E "AndroidRuntime|$PKG|ExoPlayer|AURA" | tail -200
} > "$OUT/raw/logcat.txt" 2>&1
grep -q "FATAL EXCEPTION" "$OUT/raw/logcat.txt" && log "CRASH DETECTED (see logcat.txt)"
cat "$OUT/raw/logcat.txt" | head -150
exit 0
